static bool Allowed(UNiagaraSystem* S, FString& R)
{
    if (!GIsEditor || IsRunningGame() || (GEditor && GEditor->PlayWorld)) { R=TEXT("REJECT running game/PIE"); return false; }
    if (!IsValid(S) || S->HasAnyFlags(RF_ClassDefaultObject)) { R=TEXT("REJECT null/CDO"); return false; }
    const FString P=S->GetOutermost()->GetName();
    if (P!=Slash && P!=Shotgun && P!=Giant) { R=TEXT("REJECT exact R02 package allowlist: ")+P; return false; }
    if (S->GetName()!=FPackageName::GetShortName(P) || S->GetOuter()!=S->GetOutermost()) { R=TEXT("REJECT non-root or mismatched system object"); return false; }
    return true;
}
static TArray<UNiagaraScript*> Scripts(UNiagaraSystem* S)
{
    TArray<UNiagaraScript*> Out;
    for (const FNiagaraEmitterHandle& H:S->GetEmitterHandles())
        if (const FVersionedNiagaraEmitterData* D=H.GetEmitterData())
        {
            TArray<UNiagaraScript*> Local; D->GetScripts(Local,false,false);
            for (UNiagaraScript* Script:Local) if (Script) Out.AddUnique(Script);
        }
    return Out;
}
