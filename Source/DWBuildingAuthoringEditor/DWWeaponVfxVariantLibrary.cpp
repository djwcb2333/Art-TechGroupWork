bool UDWWeaponVfxVariantLibrary::ApplyApprovedR02Edits(UNiagaraSystem* S,FString& R)
{
    using namespace DWApprovedVfx;
    R.Reset(); if (!Allowed(S,R)) return false;
    const FString Path=S->GetOutermost()->GetName();
    if (Path==Slash) { R=TEXT("NO_OP Slash material/renderer operation is separate."); return true; }
    TArray<FEdit> Edits;
    if (Path==Shotgun)
        Edits={
            {TEXT("Constants.BulletFire1.AddVelocityInCone.Cone Axis"),false,FVector3f(1,0,0),0.f},
            {TEXT("Constants.MuzzleFlash.OrientMeshToVector.Look At Direction"),false,FVector3f(1,0,0),0.f},
            {TEXT("Constants.MuzzleFlash.OrientMeshToVector.Reference Axis Vector"),false,FVector3f(1,0,0),0.f},
            {TEXT("Constants.MuzzleFlash.OrientMeshToVector.Side Axis Direction"),false,FVector3f(0,1,0),0.f},
            {TEXT("Constants.MuzzleFlash.OrientMeshToVector.Up Axis Direction"),false,FVector3f(0,0,1),0.f}};
    else Edits.Add({TEXT("Constants.Dust.EmitterState.Loop Delay"),true,FVector3f::ZeroVector,0.f});
    TArray<FTarget> Targets; TArray<int32> Counts; Counts.Init(0,Edits.Num());
    // Preflight EVERY required full name/type/store before ANY mutation.
    for (UNiagaraScript* Script:Scripts(S))
    {
        TArray<FNiagaraVariable> Vars; Script->RapidIterationParameters.GetParameters(Vars);
        for (int32 E=0;E<Edits.Num();++E)
        {
            int32 Matches=0;
            for (const FNiagaraVariable& V:Vars)
            {
                if (V.GetName().ToString()!=Edits[E].Name) continue;
                ++Matches;
                const FNiagaraTypeDefinition T=Edits[E].bFloat?FNiagaraTypeDefinition::GetFloatDef():FNiagaraTypeDefinition::GetVec3Def();
                if (V.GetType()!=T || Script->GetOutermost()!=S->GetOutermost() || Script->RapidIterationParameters.IndexOf(V)==INDEX_NONE)
                { R=TEXT("REJECT type/offset/ownership: ")+Script->GetPathName()+TEXT(" ")+Edits[E].Name; return false; }
                Targets.Add({Script,V,E}); ++Counts[E];
            }
            if (Matches>1) { R=TEXT("REJECT ambiguous full name within store: ")+Edits[E].Name; return false; }
        }
    }
    for (int32 E=0;E<Edits.Num();++E)
        if (Counts[E]==0) { R=TEXT("REJECT missing typed RI: ")+Edits[E].Name; return false; }
    S->Modify(); TSet<UNiagaraScript*> Modified;
    for (const FTarget& Target:Targets)
    {
        if (!Modified.Contains(Target.Script)) { Target.Script->Modify(); Modified.Add(Target.Script); }
        FNiagaraParameterStore& Store=Target.Script->RapidIterationParameters;
        const FEdit& Edit=Edits[Target.Edit]; bool bSet=false;
        if (Edit.bFloat)
        {
            const float Old=Store.GetParameterValue<float>(Target.Variable);
            bSet=Store.SetParameterValue<float>(Edit.F,Target.Variable,false);
            R+=FString::Printf(TEXT("%s %s float %g -> %g readback=%g\n"),*Target.Script->GetPathName(),*Edit.Name,Old,Edit.F,Store.GetParameterValue<float>(Target.Variable));
        }
        else
        {
            const FVector3f Old=Store.GetParameterValue<FVector3f>(Target.Variable);
            bSet=Store.SetParameterValue<FVector3f>(Edit.V,Target.Variable,false);
            const FVector3f Read=Store.GetParameterValue<FVector3f>(Target.Variable);
            R+=FString::Printf(TEXT("%s %s Vec3 (%g,%g,%g) -> (%g,%g,%g) readback=(%g,%g,%g)\n"),*Target.Script->GetPathName(),*Edit.Name,Old.X,Old.Y,Old.Z,Edit.V.X,Edit.V.Y,Edit.V.Z,Read.X,Read.Y,Read.Z);
        }
        if (!bSet) { R+=TEXT("ERROR unexpected setter failure: do not save; reload clone.\n"); return false; }
    }
    S->MarkPackageDirty(); const bool bRequest=S->RequestCompile(true);
    R+=FString::Printf(TEXT("Compile request returned=%d; NOT compilation success; no save.\n"),bRequest);
    if (Path==Giant) R+=TEXT("INCOMPLETE_SECTOR: only Dust delay changed; Box remains.\n");
    return true;
}

bool UDWWeaponVfxVariantLibrary::InspectApprovedR02Inputs(UNiagaraSystem* S,FString& R)
{
    using namespace DWApprovedVfx;
    R.Reset(); if (!Allowed(S,R)) return false;
    for (UNiagaraScript* Script:Scripts(S))
    {
        R+=TEXT("SCRIPT ")+Script->GetPathName()+TEXT("\n");
        for (const FNiagaraVariableWithOffset& V:Script->RapidIterationParameters.ReadParameterVariables())
            R+=TEXT(" RI ")+V.GetName().ToString()+TEXT(" type=")+V.GetType().GetName()+TEXT("\n");
    }
    UNiagaraScript* Shape=LoadObject<UNiagaraScript>(nullptr,TEXT("/Niagara/Modules/Spawn/Location/V2/ShapeLocation.ShapeLocation"));
    UNiagaraScriptSource* Source=Shape?Cast<UNiagaraScriptSource>(Shape->GetLatestSource()):nullptr;
    if (!Source || !Source->NodeGraph) { R+=TEXT("REJECT missing ShapeLocation source\n"); return false; }
    // Read the original persistent graph only. Stack input traversal requires a real emitter context.
    // No temporary function call, default-pin allocation, constant resolver or traversal cache.
    const UNiagaraGraph* ShapeGraph=Source->NodeGraph;
    for (const auto& Pair:ShapeGraph->GetAllMetaData())
    {
        const FNiagaraVariable& Input=Pair.Key;
        const UEnum* Enum=Input.GetType().GetEnum();
        R+=FString::Printf(TEXT("SHAPE_DECLARED input=%s type=%s enum=%s\n"),
            *Input.GetName().ToString(),*Input.GetType().GetName(),*GetPathNameSafe(Enum));
        if (Enum) for (int32 I=0;I<Enum->NumEnums();++I)
            R+=FString::Printf(TEXT(" enum %lld=%s display=%s\n"),Enum->GetValueByIndex(I),*Enum->GetNameStringByIndex(I),*Enum->GetDisplayNameTextByIndex(I).ToString());
        const TOptional<FNiagaraVariableMetaData> Meta=ShapeGraph->GetMetaData(Input);
        if (Meta.IsSet())
        {
            R+=TEXT(" description=")+Meta->Description.ToString()+TEXT("\n");
            for (const auto& Entry:Meta->PropertyMetaData) R+=TEXT(" metadata ")+Entry.Key.ToString()+TEXT("=")+Entry.Value+TEXT("\n");
        }
    }
    for (const UEdGraphNode* Node:ShapeGraph->Nodes)
    {
        if (!Node) continue;
        R+=TEXT("SHAPE_NODE ")+Node->GetPathName()+TEXT(" class=")+Node->GetClass()->GetPathName()+TEXT("\n");
        for (const UEdGraphPin* Pin:Node->Pins) PinReport(Pin,TEXT("SHAPE_SOURCE ")+Node->GetName(),R);
    }
    R+=TEXT("READ_ONLY_RAW_GRAPH: no resolved stack visibility or context evaluation; absent unit metadata means UNKNOWN. No graph modified, compiled or saved.\n");
    return true;
}

