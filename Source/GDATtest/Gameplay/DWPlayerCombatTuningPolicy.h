inline bool A01ValueAllowed(FName Id,double Value)
{
 if(!A01Allowed(Id)||!FMath::IsFinite(Value)||Value<0.||Value>MAX_flt)return false;
 const FString Key=Id.ToString();return !Key.EndsWith(TEXT("_m"))||Value<=static_cast<double>(MAX_flt)/100.;
}
struct FSimpleValues {double Damage=0.,Interval=0.,Range=0.;};
inline bool ResolveSimple(const FSimpleValues& Base,bool OverrideDamage,bool OverrideInterval,bool OverrideRange,const FSimpleValues& Config,FSimpleValues& Out)
{
 FSimpleValues C{OverrideDamage?Config.Damage:Base.Damage,OverrideInterval?Config.Interval:Base.Interval,OverrideRange?Config.Range:Base.Range};
 if(!FMath::IsFinite(C.Damage)||C.Damage<0.||C.Damage>MAX_flt||!FMath::IsFinite(C.Interval)||C.Interval<=0.||C.Interval>MAX_flt||!FMath::IsFinite(C.Range)||C.Range<=0.||C.Range>MAX_flt)return false;
 Out=C;return true;
}
